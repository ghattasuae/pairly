/**
 * Regenerate the API types from the FastAPI OpenAPI document.
 *
 *   pnpm gen:api                       # build the schema from the API code (no server)
 *   pnpm gen:api --url http://localhost:8000/v1/openapi.json   # from a running API
 *
 * Writes two committed files:
 *   openapi/v1.json            the schema snapshot (sorted keys, stable diffs)
 *   src/generated/api.ts       openapi-typescript output
 *
 * CI can run this and fail on `git diff --exit-code` to catch a stale snapshot.
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, "..");
const repo = resolve(pkg, "../..");

function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((k) => [k, sortKeys(value[k])]),
    );
  }
  return value;
}

async function loadSchema() {
  const urlFlag = process.argv.indexOf("--url");
  if (urlFlag !== -1) {
    const url = process.argv[urlFlag + 1];
    if (!url) throw new Error("--url needs a value");
    const response = await fetch(url, { headers: { accept: "application/json" } });
    if (!response.ok) throw new Error(`GET ${url}: HTTP ${response.status}`);
    return response.json();
  }
  const result = spawnSync("uv", ["run", "--quiet", "python", "packages/shared-ts/scripts/dump_openapi.py"], {
    cwd: repo,
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  });
  if (result.status !== 0) {
    throw new Error(`dump_openapi.py failed:\n${result.stderr || result.error}`);
  }
  return JSON.parse(result.stdout);
}

const schema = sortKeys(await loadSchema());
mkdirSync(resolve(pkg, "openapi"), { recursive: true });
writeFileSync(resolve(pkg, "openapi/v1.json"), `${JSON.stringify(schema, null, 2)}\n`);

const ast = await openapiTS(schema, { alphabetize: true, exportType: true });
const header = [
  "// SPDX-License-Identifier: AGPL-3.0-only",
  "// Copyright (c) 2026 Proofly Technology",
  "// @generated by packages/shared-ts/scripts/gen-api.mjs from openapi/v1.json. DO NOT EDIT.",
  "",
].join("\n");
mkdirSync(resolve(pkg, "src/generated"), { recursive: true });
writeFileSync(resolve(pkg, "src/generated/api.ts"), `${header}\n${astToString(ast)}`);
console.log("wrote packages/shared-ts/openapi/v1.json and src/generated/api.ts");
