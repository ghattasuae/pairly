"""Recorded responses for the Pay invoice extraction (``data/recordings.json``).

The bundle is generated by ``uv run python -m synth.pay recordings`` from the synthetic
ground truth: the answers are **scripted, labelled as such**, not model output. It
covers an eval subset (digital PDFs per layout, DOCX, invoices in an email body) and the
demo trio, so the ``pay_invoice`` graph runs offline in ``recorded`` mode for exactly
those documents. Any other document finds no recording and goes to a person.
"""

from __future__ import annotations

import uuid
from importlib.resources import files

from sqlalchemy.ext.asyncio import AsyncSession

from pairly_core.llm.bundle import ImportReport, import_recordings, parse_bundle


def recordings_text() -> str:
    return files("pairly_pay").joinpath("data", "recordings.json").read_text(encoding="utf-8")


async def import_pay_recordings(session: AsyncSession, org_id: uuid.UUID) -> ImportReport:
    """Import the bundle for ``org_id`` (idempotent), in the caller's transaction."""
    return await import_recordings(session, org_id, parse_bundle(recordings_text()))
