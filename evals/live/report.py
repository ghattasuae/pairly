"""The "Live baseline" section of ``evals/report.md``, generated from
``evals/results/hire_live.json`` and ``evals/results/pay_live.json``.

Every number comes from those files. A suite that stopped early or lost a document is
shown as partial with its sample size. Targets are the brief's (section 7.2); where the
brief sets none, the threshold is to be set by the founder after this baseline
(``threshold: after_first_live_baseline`` in ``evals/thresholds.yaml``, unchanged here).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Final

from evals.live.harness import RECORDINGS_DIR, RESULTS_DIR, ROOT, read_recording_lines

REPORT: Final = ROOT / "evals" / "report.md"
BEGIN: Final = "<!-- BEGIN live (generated by python -m evals.live report; do not edit) -->"
END: Final = "<!-- END live -->"
NO_TARGET: Final = "none set (after first live baseline)"


def _load(name: str) -> dict[str, Any]:
    path = RESULTS_DIR / name
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}


def recorded_spend() -> tuple[float, int]:
    """What every live call cost, from the recordings (each paid call is recorded once,
    when it is made; replays are not recorded again). Provider errors cost nothing."""
    micros = calls = 0
    products = {
        p.name.split("_live.jsonl", 1)[0]
        for p in RECORDINGS_DIR.glob("*_live.jsonl*")
        if p.name.endswith(("_live.jsonl", "_live.jsonl.xz"))
    }
    for product in sorted(products):
        for line in read_recording_lines(RECORDINGS_DIR / f"{product}_live.jsonl"):
            micros += int(json.loads(line)["measured"]["cost_micros"])
            calls += 1
    return micros / 1e6, calls


def _fmt(value: Any, unit: str = "") -> str:
    if value is None:
        return "not measured"
    if isinstance(value, float):
        return f"{value:.4g}{unit}"
    return f"{value}{unit}"


def _ms(value: Any) -> str:
    return "not measured" if value is None else f"{round(value)}"


def _usd(value: Any) -> str:
    return "not measured" if value is None else f"{value:.4f}"


def _models(usage: dict[str, Any]) -> str:
    models = usage.get("models_returned_by_api") or usage.get("models") or {}
    return ", ".join(f"{m} ({n})" for m, n in sorted(models.items())) or "none"


def _row(
    metric: str, value: str, n: str, suite: dict[str, Any], target: str, usage_key: str = ""
) -> str:
    usage = suite.get("usage", {})
    if usage_key:
        usage = {**usage, **usage.get("per_task", {}).get(usage_key, {})}
    lat = usage.get("latency_per_document", {})
    status = suite.get("status", "not run")
    return (
        f"| {metric} | {value} | {n} | {status} | {target} | {_models(suite.get('usage', {}))} "
        f"| {usage.get('input_tokens', 0)} / {usage.get('output_tokens', 0)} "
        f"| {_usd(usage.get('cost_usd_measured'))} "
        f"| {_ms(lat.get('p50_ms'))} / {_ms(lat.get('p95_ms'))} |"
    )


def section(hire: dict[str, Any], pay: dict[str, Any]) -> str:
    suites = {
        "hire-extraction": hire.get("extraction", {}),
        "hire-fairness": hire.get("fairness", {}),
        "hire-injection": hire.get("injection", {}),
        "pay-extraction": pay.get("extraction", {}),
    }
    ran = {k: v for k, v in suites.items() if v}
    dates = sorted(v["run"]["date"] for v in ran.values())
    spent, calls = recorded_spend()
    models: dict[str, int] = {}
    for v in ran.values():
        for m, n in (v["usage"].get("models_returned_by_api") or {}).items():
            models[m] = models.get(m, 0) + n
    lines = [
        BEGIN,
        "## Live baseline (`python -m evals.live`)",
        "",
        "The model-dependent metrics measured with a real model (Anthropic, small tier "
        "first with escalation, and response reuse for identical requests, as in "
        "production). Synthetic data only; labels are rule-based, not human judgments. "
        "Recorded responses (`evals/recordings/*_live.jsonl.xz`, committed) make a second "
        "run free on any machine. These numbers do not gate: `hire.json` keeps "
        "`pending_live_run` and `thresholds.yaml` is unchanged until the founder sets "
        "thresholds; the Brief target column is what the founder decides against.",
        "",
        f"- Date (UTC): {dates[0] if dates else 'not run'}"
        + (f" to {dates[-1]}" if len(dates) > 1 else ""),
        "- Models answering (API model id, calls used per suite, replays included): "
        + (", ".join(f"`{m}` ({n})" for m, n in sorted(models.items())) or "none"),
        f"- Total spent on live calls (from the recordings, smoke runs included): "
        f"{spent:.4f} USD over {calls} calls",
        "- Status per suite: "
        + ", ".join(f"{k} {v.get('status', 'not run')}" for k, v in suites.items()),
        "",
        "| Metric | Value | n | Status | Brief target | Models (calls) | Tokens in / out "
        "| Cost USD | Latency per doc p50 / p95 ms |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    ext = suites["hire-extraction"]
    if ext:
        acc = ext["extraction_model_accuracy"]
        agr = ext["rubric_agreement"]
        ev = ext["evidence_validity"]
        n_cv = f"{acc['cvs']} CVs, {acc['values']} values"
        lines += [
            _row(
                "CV field extraction accuracy",
                _fmt(acc["rate"]),
                n_cv,
                ext,
                "per field; " + NO_TARGET,
            ),
            _row(
                "Rubric agreement, exact (final score)",
                _fmt(agr["final_exact_agreement"]),
                f"{agr['criteria']} criteria, {agr['cvs_scored']} CVs",
                ext,
                NO_TARGET,
            ),
            _row(
                "Rubric agreement, within one point (final)",
                _fmt(agr["final_within_one"]),
                f"{agr['criteria']} criteria",
                ext,
                NO_TARGET,
            ),
            _row(
                "Overall score mean abs error (0 to 100)",
                _fmt(agr["overall_mean_abs_error"]),
                f"{agr['cvs_scored']} CVs",
                ext,
                NO_TARGET,
            ),
            _row(
                "Evidence validity",
                _fmt(ev["rate"]),
                f"{ev['quotes']} quotes",
                ext,
                "100%",
            ),
            _row(
                "Cost per CV, mean USD",
                _usd(ext["usage"]["cost_usd_per_document"]["mean"]),
                f"{ext['usage']['documents']} CVs",
                ext,
                NO_TARGET,
            ),
        ]
    fair = suites["hire-fairness"]
    if fair:
        d = fair["model_score_delta"]
        lines += [
            _row(
                "Fairness: max overall score change per pair (all pairs, run 1)",
                _fmt(d["max_delta"]),
                f"{d['pairs']} pairs",
                fair,
                "below a set threshold; " + NO_TARGET,
            ),
            _row(
                "Fairness: mean overall score change per pair (all pairs, run 1)",
                _fmt(d["mean_delta"]),
                f"{d['pairs']} pairs",
                fair,
                NO_TARGET,
            ),
            _row(
                "Fairness: pairs with any score change (all pairs, run 1)",
                _fmt(d["pairs_with_any_change"]),
                f"{d['pairs']} pairs",
                fair,
                NO_TARGET,
            ),
        ]
        same = d.get("input_identical")
        if same:
            lines += [
                _row(
                    "Fairness, input-identical pairs: max score change",
                    _fmt(same["max_delta"]),
                    f"{same['pairs']} pairs",
                    fair,
                    "0 by construction (response reuse); below a set threshold",
                ),
            ]
        diff = d.get("input_different")
        if diff:
            lines += [
                _row(
                    f"Fairness, input-different pairs: max change of the mean of "
                    f"{diff['runs_per_cv']} runs",
                    _fmt(diff["max_delta_of_means"]),
                    f"{diff['pairs']} pairs",
                    fair,
                    "below a set threshold; " + NO_TARGET,
                ),
                _row(
                    "Fairness, input-different pairs: model noise (max spread of one CV "
                    "over its runs)",
                    _fmt(diff["max_noise"]),
                    f"{2 * diff['pairs']} CVs x {diff['runs_per_cv']} runs",
                    fair,
                    NO_TARGET,
                ),
                _row(
                    "Fairness, input-different pairs: change above the noise",
                    _fmt(diff["pairs_delta_above_noise"]),
                    f"{diff['pairs']} pairs",
                    fair,
                    NO_TARGET,
                ),
            ]
    inj = suites["hire-injection"]
    if inj:
        lines += [
            _row(
                "Classifier recall (payload removed)",
                _fmt(inj["recall_payload_removed"]),
                f"{inj['attacks']} attacks",
                inj,
                NO_TARGET,
            ),
            _row(
                "Classifier false-positive rate",
                _fmt(inj["false_positive_rate"]),
                f"{inj['clean_cvs']} clean CVs",
                inj,
                "2% (guardrails gate, all detectors)",
            ),
        ]
    pe = suites["pay-extraction"]
    if pe:
        sub = pe.get("accuracy_eval_subset_without_demo_trio")
        if sub:
            lines += [
                _row(
                    "Eval subset only: header / line / total / VAT accuracy",
                    " / ".join(
                        _fmt(sub[k], "%")
                        for k in (
                            "header_field_accuracy_pct",
                            "line_item_field_accuracy_pct",
                            "total_accuracy_pct",
                            "vat_accuracy_pct",
                        )
                    ),
                    f"{sub['invoices']} invoices",
                    pe,
                    NO_TARGET,
                )
            ]
        a = pe["accuracy"]
        lines += [
            _row(
                "Invoice header field accuracy",
                _fmt(a["header_field_accuracy_pct"], "%"),
                f"{a['invoices']} invoices, {a['header_fields']} fields",
                pe,
                NO_TARGET,
            ),
            _row(
                "Invoice line-item field accuracy",
                _fmt(a["line_item_field_accuracy_pct"], "%"),
                f"{a['line_item_fields']} fields",
                pe,
                NO_TARGET,
            ),
            _row(
                "Invoice total accuracy",
                _fmt(a["total_accuracy_pct"], "%"),
                f"{a['invoices']} invoices",
                pe,
                NO_TARGET,
            ),
            _row(
                "Invoice VAT accuracy",
                _fmt(a["vat_accuracy_pct"], "%"),
                f"{a['invoices']} invoices",
                pe,
                NO_TARGET,
            ),
            _row(
                "Cost per invoice, mean USD",
                _usd(pe["usage"]["cost_usd_per_document"]["mean"]),
                f"{pe['usage']['documents']} invoices",
                pe,
                NO_TARGET,
            ),
        ]
    lines += [
        "",
        "Tokens, cost and latency are per suite (every row of a suite shows the suite's "
        "totals). Latency per document is the sum of its model calls, made one after the "
        "other. Details per field, criterion, pair and document: "
        "`evals/results/hire_live.json`, `evals/results/pay_live.json`.",
        "",
    ]
    if pe:
        a = pe["accuracy"]
        lines.append(
            f'- Pay rows other than "Eval subset only" cover {a["invoices"]} invoices: the '
            "eval subset plus the demo trio (`synth.pay.recordings.subset_specs`). Ready "
            f"without a person: {a['extraction_ready']} of {a['invoices']}."
        )
    if ext:
        agr = ext["rubric_agreement"]
        low = sorted(agr["per_criterion"].items(), key=lambda kv: kv[1]["exact"])[:3]
        lines.append(
            "- Rubric agreement, lowest exact agreement per criterion: "
            + ", ".join(f"`{k}` {_fmt(v['exact'])} (n {v['n']})" for k, v in low)
            + f". Model's own score before no-evidence-no-credit: exact "
            f"{_fmt(agr['model_exact_agreement'])}, within one {_fmt(agr['model_within_one'])}."
        )
        rejected = ext["evidence_validity"].get("rejected_quotes", {})
        if rejected:
            lines.append(
                "- Evidence quotes the model gave that were rejected: "
                + ", ".join(f"{n} {k}" for k, n in sorted(rejected.items()))
                + " (no credit for them; every accepted quote is valid)."
            )
    if fair:
        d = fair["model_score_delta"]
        reused = fair["usage"].get("calls_reused", 0)
        lines.append(
            f"- Fairness: {d['pairs_with_byte_identical_scoring_input']} of {d['pairs']} pairs "
            "sent the scoring model byte-identical input; with response reuse they get the "
            f"same answer ({reused} calls reused), largest change "
            f"{_fmt(d['max_delta_byte_identical_input'])}. The other pairs differ in what "
            "the model reads; their change is reported next to the model's own run-to-run "
            "spread."
        )
    if inj and inj.get("classifier_unavailable"):
        lines.append(
            "- Injection: the classifier pass failed closed (`classifier_unavailable`, the "
            "document goes to a person) on " + ", ".join(inj["classifier_unavailable"]) + "."
        )
    partial = [k for k, v in ran.items() if v.get("status") != "complete"]
    for name in partial:
        v = ran[name]
        lines.append(
            f"- {name} is partial: {v['measured_documents']} of {v['planned_documents']} "
            f"documents measured; stopped by the cost cap: {v['stopped_by_cost_cap']}; "
            f"errors: {len(v['errors'])}."
        )
    lines.append(END)
    return "\n".join(lines) + "\n"


def write_live_report(path: Path = REPORT) -> None:
    block = section(_load("hire_live.json"), _load("pay_live.json"))
    current = path.read_text(encoding="utf-8")
    if BEGIN in current and END in current:
        head, rest = current.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        text = head + block.rstrip("\n") + tail
    else:
        text = current.rstrip("\n") + "\n\n" + block
    path.write_text(text if text.endswith("\n") else text + "\n", encoding="utf-8")
