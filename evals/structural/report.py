"""The "Structural checks" section of ``evals/report.md``, generated from
``evals/results/structural.json``. Only the text between the markers is replaced; every
number comes from the run."""

from __future__ import annotations

from pathlib import Path
from typing import Any, Final

from evals.hire.report import HEADER, _fmt

BEGIN: Final = "<!-- BEGIN structural (generated by python -m evals.structural; do not edit) -->"
END: Final = "<!-- END structural -->"


def _cell(metric: dict[str, Any] | None) -> str:
    if not metric:
        return "n/a"
    return f"{_fmt(metric.get('rate'))} ({metric.get('n')})"


def section(result: dict[str, Any]) -> str:
    lines = [
        BEGIN,
        "## Structural checks of the other AI components (`python -m evals.structural`)",
        "",
        "**These are structural checks, not quality judgments.** They run on the committed "
        "recordings (scripted answers, not model output) with no model call: does every "
        "recorded output fit its schema, stay clear of banned content and em dashes, pass "
        "the component's own deterministic check and point only at what its request held. "
        "Schema validity and banned content are hard rules (gated at 1.0). Nothing here says "
        "how good a draft is; that needs a live model and people.",
        "",
        "| Component | Outputs | Schema valid | Banned content free | Em dash free | Own check "
        "| References exist | Recorded on today's schema | Request chars, mean | Cost |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for c in result.get("components", {}).values():
        if c.get("status") != "measured":
            lines.append(f"| {c['title']} | 0 | no recordings | | | | | | | not measured |")
            continue
        own = c.get("product_check")
        own_cell = f"{own['name']}: {_cell(own)}" if own else "n/a"
        cost = c.get("cost", {})
        cost_cell = f"{cost.get('usd')} USD" if cost.get("status") == "measured" else "not measured"
        lines.append(
            f"| {c['title']} | {c['recorded_outputs']} | {_cell(c.get('schema_valid'))} "
            f"| {_cell(c.get('banned_content_free'))} | {_cell(c.get('em_dash_free'))} "
            f"| {own_cell} | {_cell(c.get('references_exist'))} "
            f"| {_cell(c.get('schema_current'))} "
            f"| {_fmt(c.get('size', {}).get('request_chars', {}).get('mean'))} | {cost_cell} |"
        )
    lines += [
        "",
        "Rates with the number of outputs in brackets. Cost is reported only from live "
        "recordings (scripted answers carry no tokens). Details, failures and sizes are in "
        "`evals/results/structural.json`.",
        END,
    ]
    return "\n".join(lines) + "\n"


def write_report(path: Path, result: dict[str, Any]) -> None:
    current = path.read_text(encoding="utf-8") if path.exists() else HEADER
    block = section(result)
    if BEGIN in current and END in current:
        head, rest = current.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        current = head + block.rstrip("\n") + tail
    else:
        current = current.rstrip("\n") + "\n\n" + block
    path.write_text(current, encoding="utf-8")
