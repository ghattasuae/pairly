def section(result: dict[str, Any]) -> str:
    dataset = result.get("dataset", {})
    lines = [
        BEGIN,
        "## Hire screening (`python -m evals.hire`)",
        "",
        f"Dataset: `synth.hire`, {dataset.get('count')} CVs, seed {dataset.get('seed')}; "
        f"{dataset.get('screened')} documents screened (scans "
        f"{'included' if dataset.get('scans_included') else 'skipped'}), "
        f"{len(dataset.get('errors') or [])} errors.",
        "",
        "**Model answers in this run are scripted from the synthetic ground truth, not "
        "model output.** They test everything deterministic around the model (guardrails, "
        "sanitising, evidence location, blind redaction, no evidence no credit, the overall "
        "score, claim checks, knockouts). Rubric scoring agreement with the synthetic labels "
        "is computed only for live runs: with scripted answers it would compare the labels "
        "with themselves, so it is reported as pending live run. The same holds for model "
        "extraction accuracy, model score changes across fairness pairs, the classifier's "
        "share of injection detection, model latency and cost. No API key is configured yet.",
        "",
        "| Metric | Value |",
        "| --- | --- |",
    ]
    for label, path in ROWS:
        lines.append(f"| {label} | {_fmt(_get(result, path))} |")
    lines += [
        "",
        "Per-field extraction ceilings, per-category redaction rates, claim-check rates on "
        "clean CVs and stage timings are in `evals/results/hire.json`.",
        END,
    ]
    return "\n".join(lines) + "\n"


def write_report(path: Path, result: dict[str, Any]) -> None:
    current = path.read_text(encoding="utf-8") if path.exists() else HEADER
    block = section(result)
    if BEGIN in current and END in current:
        head, rest = current.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        text = head + block.rstrip("\n") + tail
    else:
        text = current.rstrip("\n") + "\n\n" + block
    path.write_text(text if text.endswith("\n") else text + "\n", encoding="utf-8")
