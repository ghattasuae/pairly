"""The Hire section of ``evals/report.md``, generated from ``evals/results/hire.json``.

Only the text between the ``hire`` markers is replaced, so other runners can own their
own sections of the same file. Every number comes from the result of the run.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Final

BEGIN: Final = "<!-- BEGIN hire (generated by python -m evals.hire; do not edit) -->"
END: Final = "<!-- END hire -->"
HEADER: Final = (
    "# Pairly evals report\n\n"
    "Generated from the latest eval runs. Numbers quoted in the README or the docs must\n"
    "come from here. Thresholds and the gate: `evals/thresholds.yaml`,\n"
    "`uv run python -m evals.gate`.\n"
)


def _get(data: Any, path: str) -> Any:
    for part in path.split("."):
        if not isinstance(data, dict) or part not in data:
            return None
        data = data[part]
    return data


def _fmt(value: Any) -> str:
    if isinstance(value, dict) and value.get("status") == "pending_live_run":
        return "pending live run"
    if isinstance(value, float):
        return f"{value:.4f}".rstrip("0").rstrip(".") if value != int(value) else f"{value:.1f}"
    if value is None:
        return "n/a"
    return str(value)


