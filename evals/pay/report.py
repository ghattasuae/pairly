"""The Pay section of ``evals/report.md``, generated from ``evals/results/pay.json``.

Only the text between the ``pay`` markers is replaced. Every number comes from the run.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Final

from evals.hire.report import HEADER, _fmt, _get

BEGIN: Final = "<!-- BEGIN pay (generated by python -m evals.pay; do not edit) -->"
END: Final = "<!-- END pay -->"

ROWS: Final = (
    ("Duplicate detection recall", "duplicates.recall"),
    ("Duplicate detection precision", "duplicates.precision"),
    ("Suspected original is the right one", "duplicates.original_identified_rate"),
    ("Bank-mismatch recall (target 1.0)", "bank_mismatch.recall"),
    ("Lookalike-domain recall", "lookalike_domain.recall"),
    ("Arithmetic and VAT error recall", "arithmetic_vat.recall"),
    ("Arithmetic and VAT error recall, every expected type", "arithmetic_vat.type_level_recall"),
    ("Injection catch rate", "injection.catch_rate"),
    ("Clean invoices routed to review by the checks", "false_positives.review_rate"),
    ("Clean invoices with a medium or worse finding", "false_positives.flag_rate"),
    ("Attack invoices routed to review", "attacks_routed_to_review"),
    ("Check errors", "check_errors"),
)


def section(result: dict[str, Any]) -> str:
    dataset = result.get("dataset", {})
    scans = "included" if dataset.get("scans_included") else "not parsed"
    lines = [
        BEGIN,
        "## Pay validation and fraud checks (`python -m evals.pay`)",
        "",
        f"Dataset: `synth.pay`, seed {dataset.get('seed')}: {dataset.get('regular')} regular "
        f"and {dataset.get('attacks')} attack invoices; {dataset.get('parsed')} documents "
        f"parsed and scanned (scans {scans}).",
        "",
        "**The read values are the synthetic ground truth**, so these numbers measure the "
        "checks with a perfect reader, not extraction. No model runs; the spend policy search "
        "needs a live model and is not part of this run (the deterministic rule set is).",
        "",
        "| Metric | Value |",
        "| --- | --- |",
    ]
    for label, path in ROWS:
        lines.append(f"| {label} | {_fmt(_get(result, path))} |")
    lines += [
        "",
        "Recall per expected finding, misses and false positives by code are in "
        "`evals/results/pay.json`.",
        END,
    ]
    return "\n".join(lines) + "\n"


def write_report(path: Path, result: dict[str, Any]) -> None:
    current = path.read_text(encoding="utf-8") if path.exists() else HEADER
    block = section(result)
    if BEGIN in current and END in current:
        head, rest = current.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        current = head + block.rstrip("\n") + tail
    else:
        current = current.rstrip("\n") + "\n\n" + block
    path.write_text(current, encoding="utf-8")
