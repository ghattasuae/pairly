def _tiers(card: Card, prompt: Any, catalog: Any) -> tuple[str, str | None]:
    spec = _task_spec(card.task_spec) if card.task_spec else None
    if spec is not None and (spec.name, spec.prompt_version) != (card.task, card.version):
        raise SystemExit(f"{card.slug}: {card.task_spec} is {spec.name}/{spec.prompt_version}")
    max_tier = spec.max_tier if spec is not None else card.inline_max_tier
    tiers = catalog.tiers_from(prompt.tier, max_tier)
    parts = []
    for tier in tiers:
        models = [
            f"{provider} `{entry.model}`"
            for provider in catalog.provider_order
            if (entry := catalog.model_for(provider, tier)) is not None
        ]
        parts.append(f"`{tier}` ({', '.join(models)})")
    threshold = spec.confidence_threshold if spec is not None else None
    return " then ".join(parts), (None if threshold is None else json.dumps(threshold))


def render_card(card: Card, registry: Any, catalog: Any, committed: frozenset[str]) -> str:
    prompt = registry.get(card.task, card.version)
    tiers, threshold = _tiers(card, prompt, catalog)
    readings = [read_metric(m, committed) for m in card.metrics]
    lines = [
        HEADER,
        "",
        f"# Model card: {card.title}",
        "",
        "| | |",
        "|---|---|",
        f"| Purpose | {card.purpose} |",
        f"| Workflow | {card.workflow} |",
        f"| Code | {card.code} |",
        f"| Prompt | `{card.task}` version `{prompt.version}`, file SHA-256 "
        f"`{prompt.hash[:16]}...` |",
        f"| Output schema | `{prompt.output_schema}` |",
        f"| Model tiers, cheapest first | {tiers} |",
        f"| Temperature | {json.dumps(prompt.temperature)} |",
        f"| Output token limit | {prompt.max_output_tokens} |",
        f"| Confidence threshold to accept | {threshold or 'none'} |",
        "",
        "## Inputs",
        "",
        card.inputs,
        "",
        "## Outputs",
        "",
        card.outputs,
        "",
        "## Human oversight",
        "",
        card.oversight,
        "",
        "## Limits",
        "",
        *(f"* {limit}" for limit in card.limits),
        "* Every call is logged in `model_calls` (prompt version and hash, model, inputs, "
        "output, tokens, cost) and fails closed: no model means a person does the step.",
        "",
        "## Evals",
        "",
    ]
    if readings:
        lines += [
            "Numbers come only from result files committed in `evals/results/`, exactly as "
            "written there. See [evals.md](../evals.md) for what each run measures. In the "
            "scripted files (`hire.json`, `pay.json`) a model metric stays pending; live "
            "numbers are read from the committed `*_live.json` files, and the ones with a "
            "founder-approved threshold (`live: true` in `evals/thresholds.yaml`) gate.",
            "",
            "| Metric | Value | Over | Run | Source |",
            "|---|---|---|---|---|",
            *(
                f"| {r.metric.label} | {r.shown} | {r.sample} | {r.run_status or ''} "
                f"| `{r.metric.file}` `{r.metric.path}` |"
                for r in readings
            ),
            "",
        ]
        notes = [f"* {r.metric.label}: {r.metric.note}" for r in readings if r.metric.note]
        if notes:
            lines += [*notes, ""]
    if card.eval_note:
        lines += [card.eval_note, ""]
    return "\n".join(lines)


def render_index(registry: Any, committed: frozenset[str]) -> str:
    lines = [
        HEADER,
        "",
        "# Model cards",
        "",
        "One card per AI component: what it is for, what it sees, what it returns, which "
        "prompt and model tier it uses, its limits, where a person oversees it, and the "
        "evals that cover it. The [risk register](risk-register.md) and the "
        "[human oversight description](human-oversight.md) cover all of them.",
        "",
        "| Component | Workflow | Prompt | Card |",
        "|---|---|---|---|",
    ]
    for card in CARDS:
        prompt = registry.get(card.task, card.version)
        lines.append(
            f"| {card.title} | {card.workflow} | `{card.task}` `{prompt.version}` "
            f"| [{card.slug}.md]({card.slug}.md) |"
        )
    lines += [
        "",
        "## Eval numbers in the cards",
        "",
        "Read from the committed result files: "
        + (", ".join(f"`{name}`" for name in sorted(committed)) or "none")
        + ". A live result file that is not committed yet is reported as pending.",
        "",
        "| Component | Metric | Value | Over | Source file |",
        "|---|---|---|---|---|",
    ]
    for card in CARDS:
        for metric in card.metrics:
            r = read_metric(metric, committed)
            lines.append(
                f"| {card.title} | {metric.label} | {r.shown} | {r.sample} | `{metric.file}` |"
            )
    lines.append("")
    return "\n".join(lines)


def render() -> dict[str, str]:
    registry, catalog, committed = _registry(), _catalog(), committed_results()
    files = {f"{c.slug}.md": render_card(c, registry, catalog, committed) for c in CARDS}
    files["README.md"] = render_index(registry, committed)
    return files


def stale(out: Path = OUT) -> list[str]:
    wanted = render()
    changed = [
        name
        for name, text in wanted.items()
        if not (out / name).is_file() or (out / name).read_text(encoding="utf-8") != text
    ]
    extra = (
        [p.name for p in out.glob("*.md") if p.name not in wanted and p.name not in STATIC]
        if out.is_dir()
        else []
    )
    return sorted(changed + extra)


def write(out: Path = OUT) -> list[str]:
    out.mkdir(parents=True, exist_ok=True)
    wanted = render()
    for p in out.glob("*.md"):
        if p.name not in wanted and p.name not in STATIC:
            p.unlink()
    for name, text in wanted.items():
        (out / name).write_text(text, encoding="utf-8")
    return sorted(wanted)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="fail if a file would change")
    args = parser.parse_args(argv)
    if args.check:
        changed = stale()
        for name in changed:
            print(f"docs/model-cards/{name} is out of date", file=sys.stderr)
        if changed:
            print("run: uv run python -m scripts.model_cards", file=sys.stderr)
        return 1 if changed else 0
    for name in write():
        print(f"docs/model-cards/{name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
