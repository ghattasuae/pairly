def committed_results() -> frozenset[str]:
    """Result files tracked by git (a local, uncommitted run is never read)."""
    out = subprocess.run(
        ["git", "ls-files", "--", "evals/results"],  # noqa: S607 (git from PATH)
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return frozenset(Path(line).name for line in out.splitlines() if line.endswith(".json"))


def lookup(data: Any, path: str) -> tuple[bool, Any]:
    for part in path.split("."):
        if not isinstance(data, dict) or part not in data:
            return False, None
        data = data[part]
    return True, data


@dataclass(frozen=True, slots=True)
class Reading:
    metric: Metric
    status: str  # measured, pending, not_committed, not_reported
    value: Any = None
    n: Any = None
    run_status: str | None = None

    @property
    def sample(self) -> str:
        if self.n is None:
            return ""
        return f"{json.dumps(self.n)} {self.metric.n_unit}".strip()

    @property
    def shown(self) -> str:
        if self.status == "measured":
            return json.dumps(self.value)
        return {
            "pending": "pending a live run",
            "not_committed": "pending a live run (result file not committed)",
            "not_reported": "not in the result file",
        }[self.status]


def read_metric(metric: Metric, committed: frozenset[str], results: Path = RESULTS) -> Reading:
    if metric.file not in committed or not (results / metric.file).is_file():
        return Reading(metric, "not_committed")
    data = json.loads((results / metric.file).read_text(encoding="utf-8"))
    found, value = lookup(data, metric.path)
    if not found:
        return Reading(metric, "not_reported")
    if isinstance(value, dict) and value.get("status") == PENDING:
        return Reading(metric, "pending")
    if isinstance(value, bool) or not isinstance(value, int | float):
        return Reading(metric, "not_reported")
    n = lookup(data, metric.n_path)[1] if metric.n_path else None
    run = lookup(data, f"{metric.suite}.status")[1] if metric.suite else None
    return Reading(
        metric,
        "measured",
        value,
        n=n if isinstance(n, int) and not isinstance(n, bool) else None,
        run_status=run if isinstance(run, str) else None,
    )


def _registry() -> Any:
    from pairly_core.llm.prompt_registry import PromptRegistry, core_prompt_root
    from pairly_core.plugins import discover_plugins, plugin_prompt_roots

    roots = [core_prompt_root(), *plugin_prompt_roots(discover_plugins().values())]
    return PromptRegistry(roots)


def _catalog() -> Any:
    from pairly_core.llm.catalog import load_catalog, load_prices

    return load_catalog(load_prices())


def _task_spec(path: str) -> Any:
    module, attr = path.split(":")
    return getattr(importlib.import_module(module), attr)


