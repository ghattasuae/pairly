"""Write one model card per AI component into ``docs/model-cards/``.

    uv run python -m scripts.model_cards           # write the cards and the index
    uv run python -m scripts.model_cards --check   # exit 1 if a file would change

Nothing in a card that comes from the code or an eval is typed by hand:

* the prompt version, starting tier, temperature, output limit, output schema and file
  hash come from the prompt registry (core and every plugin's ``prompt_roots``), so a
  card names a prompt that exists or the script fails;
* the confidence threshold and the highest tier come from the component's ``TaskSpec``;
* the model behind each tier comes from the model catalog (``llm/data/models.yaml``);
* every eval number is read from a result file in ``evals/results/`` that is committed
  to git (``git ls-files``). A file that exists only locally (a live run not committed
  yet) is reported as not committed, never read. A value ``{"status":
  "pending_live_run"}`` is reported as pending. Numbers are printed exactly as the file
  holds them.

The words (purpose, inputs, outputs, limits, oversight) are written here, next to the
code they describe. ``risk-register.md`` and ``human-oversight.md`` in the same folder
are written by hand and left alone. A test regenerates the cards and fails on any
difference, so a new result file or a prompt change shows up as a stale card.
"""

