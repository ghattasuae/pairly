@dataclass(frozen=True, slots=True)
class Metric:
    label: str
    file: str
    path: str
    note: str = ""
    # Where the file says how many items the number is over, and what they are.
    n_path: str | None = None
    n_unit: str = ""

    @property
    def suite(self) -> str | None:
        """The live suite's key (its ``status`` says complete or partial)."""
        return self.path.split(".")[0] if self.file.endswith("_live.json") else None


@dataclass(frozen=True, slots=True)
class Card:
    slug: str
    title: str
    workflow: str
    task: str
    version: str
    code: str
    purpose: str
    inputs: str
    outputs: str
    oversight: str
