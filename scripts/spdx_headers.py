"""Check or fix the SPDX license header of every source file, per directory.

Usage:
    python scripts/spdx_headers.py --check          # exit 1 and list files that need attention
    python scripts/spdx_headers.py --fix            # insert or correct headers
    python scripts/spdx_headers.py --check a.py b.ts  # only look at the given files

With no paths, the file list is every tracked file plus every untracked file
that git does not ignore (`git ls-files` and `git ls-files --others --exclude-standard`).

The license policy (see LICENSING.md):

    sdks/python/, sdks/typescript/, docs/quickstarts/
        Apache-2.0
    everything else
        AGPL-3.0-only OR LicenseRef-Proofly-Commercial

The header is two comment lines, written with the comment syntax of the file type,
for example in Python:

    # SPDX-License-Identifier: AGPL-3.0-only OR LicenseRef-Proofly-Commercial
    # Copyright (c) 2026 Proofly Technology

Source files (the extensions in COMMENT_STYLES) must carry the header. Other text
files (Dockerfiles, TOML, Makefile, prompt files) are checked only when they already
carry a Proofly header near the top, and then must name the license of their folder.

`--fix` inserts a missing header and rewrites a Proofly header that names the wrong
license for its folder. Shebang lines, Python encoding lines and CSS `@charset` rules
stay on top. A file that carries a third-party SPDX identifier (MIT, CC0-1.0, ...) is
reported and never changed.

Prompt files (`prompts/<task>/v<n>.md`) are pinned by the SHA-256 of the whole file
(pairly_core.llm.prompt_registry), so a published version keeps the header it was
published with: AGPL-3.0-only is accepted there and never rewritten. The copyright
holder offers those files under the same dual license as the rest of the server.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

DUAL = "AGPL-3.0-only OR LicenseRef-Proofly-Commercial"
APACHE = "Apache-2.0"
LEGACY_AGPL = "AGPL-3.0-only"
DEFAULT_LICENSE = DUAL

# Folders whose files are Apache-2.0 (client code meant to be embedded anywhere).
# The first matching prefix wins; everything else gets DEFAULT_LICENSE.
DIRECTORY_POLICY: tuple[tuple[str, str], ...] = (
    ("sdks/python/", APACHE),
    ("sdks/typescript/", APACHE),
    ("docs/quickstarts/", APACHE),
)

# License expressions Proofly puts on its own files. A header naming one of these but
# not the folder's license is fixable; any other identifier is third-party code.
OWN_LICENSES = frozenset({DUAL, APACHE, LEGACY_AGPL})

COPYRIGHT = "Copyright (c) 2026 Proofly Technology"

# Kept for callers that import the old name: the default license of the repository.
LICENSE_ID = DEFAULT_LICENSE

# How many lines from the top we search for an existing header.
HEADER_SEARCH_LINES = 10

# Comment syntax per file extension: (prefix, suffix).
COMMENT_STYLES: dict[str, tuple[str, str]] = {
    ".py": ("# ", ""),
    ".sh": ("# ", ""),
    ".yaml": ("# ", ""),
    ".yml": ("# ", ""),
    ".ts": ("// ", ""),
    ".tsx": ("// ", ""),
    ".js": ("// ", ""),
    ".mjs": ("// ", ""),
    ".cjs": ("// ", ""),
    ".css": ("/* ", " */"),
    ".sql": ("-- ", ""),
}

SKIP_DIR_PARTS = frozenset(
    {
        "node_modules",
        ".venv",
        "venv",
        ".git",
        "dist",
        "build",
        ".next",
        ".turbo",
        "coverage",
        "__pycache__",
        ".mypy_cache",
        ".ruff_cache",
        ".pytest_cache",
        "generated",
        "__generated__",
        # Third-party code kept verbatim under its own license (infra/api-docs/vendor).
        "vendor",
    }
)

SKIP_FILE_NAMES = frozenset(
    {
        "LICENSE",
        "NOTICE",
        "BRIEF.md",
        "uv.lock",
        "pnpm-lock.yaml",
        "package-lock.json",
        "yarn.lock",
        "poetry.lock",
        "Cargo.lock",
        "next-env.d.ts",
    }
)

# Suffix patterns for generated or minified files.
SKIP_NAME_SUFFIXES = (".lock", ".min.js", ".min.css", ".gen.ts", ".gen.js")

# Markers that say a file is generated and must not be edited by hand.
GENERATED_MARKERS = ("@generated", "DO NOT EDIT", "Code generated by")

# Prompt files are hashed whole; a published version keeps its original header.
HASH_PINNED_RE = re.compile(r"(?:^|/)prompts/[^/]+/v\d+\.md$")

# The identifier runs to the end of the line, minus a closing comment marker.
SPDX_RE = re.compile(r"SPDX-License-Identifier:[ \t]*(?P<id>.*?)[ \t]*(?:\*/|-->)?[ \t]*$")
COPYRIGHT_RE = re.compile(r"Copyright \(c\) \d{4}(?:-\d{4})? Proofly Technology")
# PEP 263 encoding declaration.
ENCODING_RE = re.compile(r"^[ \t\f]*#.*?coding[:=][ \t]*[-\w.]+")


@dataclass(frozen=True)
class Result:
    """Outcome of checking one file."""

    path: Path
    # "ok", "missing", "wrong-license" (fixable), "other-license" (third party), "skipped"
    status: str
    detail: str = ""
    expected: str = DEFAULT_LICENSE


def _posix(path: PurePosixPath | Path | str) -> str:
    text = str(path).replace("\\", "/")
    return text[2:] if text.startswith("./") else text


def expected_license(rel_path: PurePosixPath | Path | str) -> str:
    """The license a repository-relative path must carry."""
    posix = _posix(rel_path)
    for prefix, license_id in DIRECTORY_POLICY:
        if posix.startswith(prefix):
            return license_id
    return DEFAULT_LICENSE


def accepted_licenses(rel_path: PurePosixPath | Path | str) -> frozenset[str]:
    """Every expression accepted for a path: its policy license, plus legacy for pinned files."""
    expected = expected_license(rel_path)
    if HASH_PINNED_RE.search(_posix(rel_path)) and expected == DUAL:
        return frozenset({expected, LEGACY_AGPL})
    return frozenset({expected})


def header_lines(suffix: str, license_id: str = DEFAULT_LICENSE) -> list[str]:
    """Return the two header lines for a file extension, without line endings."""
    prefix, end = COMMENT_STYLES[suffix]
    return [
        f"{prefix}SPDX-License-Identifier: {license_id}{end}",
        f"{prefix}{COPYRIGHT}{end}",
    ]


def _skipped_path(p: PurePosixPath) -> bool:
    # License texts (LICENSES/ at the root) are kept verbatim.
    if p.parts and p.parts[0] == "LICENSES":
        return True
    if p.name in SKIP_FILE_NAMES:
        return True
    if any(part in SKIP_DIR_PARTS for part in p.parts[:-1]):
        return True
    return p.name.lower().endswith(SKIP_NAME_SUFFIXES)


def is_candidate(path: PurePosixPath | Path) -> bool:
    """True when the path is a source file type that must carry a header."""
    p = PurePosixPath(str(path).replace("\\", "/"))
    if _skipped_path(p):
        return False
    return p.suffix.lower() in COMMENT_STYLES


def is_secondary(path: PurePosixPath | Path) -> bool:
    """True for other text files: checked only when they carry a Proofly header."""
    p = PurePosixPath(str(path).replace("\\", "/"))
    return not _skipped_path(p) and p.suffix.lower() not in COMMENT_STYLES


def looks_generated(text: str) -> bool:
    head = "\n".join(text.splitlines()[:HEADER_SEARCH_LINES])
    return any(marker in head for marker in GENERATED_MARKERS)


def _preamble_length(lines: Sequence[str], suffix: str) -> int:
    """Number of leading lines that must stay above the header."""
    count = 0
    if lines and lines[0].startswith("#!"):
        count = 1
    if suffix == ".py":
        # PEP 263: the encoding line may be on line 1 or 2.
        for idx in range(count, min(2, len(lines))):
            if ENCODING_RE.match(lines[idx]):
                count = idx + 1
                break
    if suffix == ".css" and lines and lines[0].lstrip().startswith("@charset"):
        count = 1
    return count


def _spdx_ids(head: Sequence[str]) -> list[str]:
    ids = []
    for line in head:
        match = SPDX_RE.search(line)
        if match:
            ids.append(match.group("id"))
    return ids


def inspect_text(
    text: str,
    expected: str = DEFAULT_LICENSE,
    accepted: Iterable[str] | None = None,
) -> tuple[str, str]:
    """Classify file text against the license its folder needs. Returns (status, detail)."""
    allowed = frozenset(accepted) if accepted is not None else frozenset({expected})
    head = text.splitlines()[:HEADER_SEARCH_LINES]
    ids = _spdx_ids(head)
    has_copyright = any(COPYRIGHT_RE.search(line) for line in head)
    if not ids:
        return "missing", "no SPDX line"
    for found in ids:
        if found not in OWN_LICENSES:
            return "other-license", f"SPDX identifier is {found}"
    wrong = [found for found in ids if found not in allowed]
    if wrong:
        return "wrong-license", f"SPDX identifier is {wrong[0]}, this folder needs {expected}"
    if not has_copyright:
        return "missing", "no Proofly Technology copyright line"
    return "ok", ""


def _retag(line: str, license_id: str) -> str:
    """Rewrite the license expression of one SPDX line, keeping comment syntax and newline."""
    body = line.rstrip("\r\n")
    ending = line[len(body) :]
    match = SPDX_RE.search(body)
    if match is None:
        return line
    start, end = match.span("id")
    return body[:start] + license_id + body[end:] + ending


def add_header(text: str, suffix: str, license_id: str = DEFAULT_LICENSE) -> str:
    """Return text with a correct header. Text that already has one is returned unchanged.

    A missing header is inserted, a missing copyright line is added under the SPDX
    line, and a Proofly SPDX line that names another of our licenses is rewritten.
    """
    status, _ = inspect_text(text, license_id)
    if status not in {"missing", "wrong-license"}:
        return text
    newline = "\r\n" if "\r\n" in text else "\n"
    lines = text.splitlines(keepends=True)

    if status == "wrong-license":
        for idx in range(min(HEADER_SEARCH_LINES, len(lines))):
            match = SPDX_RE.search(lines[idx].rstrip("\r\n"))
            if match and match.group("id") in OWN_LICENSES:
                lines[idx] = _retag(lines[idx], license_id)
        text = "".join(lines)
        if inspect_text(text, license_id)[0] != "missing":
            return text
        lines = text.splitlines(keepends=True)

    bare = [line.rstrip("\r\n") for line in lines]
    keep = _preamble_length(bare, suffix)

    # A file that has the SPDX line but not the copyright line: add the copyright under it.
    for idx, line in enumerate(bare[:HEADER_SEARCH_LINES]):
        if SPDX_RE.search(line):
            copyright_line = header_lines(suffix, license_id)[1] + newline
            if not lines[idx].endswith(("\n", "\r")):
                lines[idx] += newline
            lines.insert(idx + 1, copyright_line)
            return "".join(lines)

    header = [line + newline for line in header_lines(suffix, license_id)]
    before = lines[:keep]
    after = lines[keep:]
    if before and not before[-1].endswith(("\n", "\r")):
        before[-1] += newline
    if after and after[0].strip():
        header.append(newline)
    return "".join(before + header + after)


def retag_text(text: str, license_id: str) -> str:
    """Rewrite every Proofly SPDX line near the top to license_id (any file type)."""
    lines = text.splitlines(keepends=True)
    for idx in range(min(HEADER_SEARCH_LINES, len(lines))):
        match = SPDX_RE.search(lines[idx].rstrip("\r\n"))
        if match and match.group("id") in OWN_LICENSES:
            lines[idx] = _retag(lines[idx], license_id)
    return "".join(lines)


def _read(path: Path) -> tuple[str | None, str]:
    if not path.is_file():
        return None, "not a file"
    try:
        text = path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError) as exc:
        return None, f"unreadable: {exc.__class__.__name__}"
    if not text.strip():
        return None, "empty file"
    return text, ""


def check_file(path: Path, rel: PurePosixPath | Path | str | None = None) -> Result:
    """Check one source file (a COMMENT_STYLES type) against its folder's license."""
    rel = rel if rel is not None else path
    expected = expected_license(rel)
    text, why = _read(path)
    if text is None:
        return Result(path, "skipped", why, expected)
    if looks_generated(text):
        return Result(path, "skipped", "generated file", expected)
    status, detail = inspect_text(text, expected, accepted_licenses(rel))
    return Result(path, status, detail, expected)


def check_secondary(path: Path, rel: PurePosixPath | Path | str | None = None) -> Result:
    """Check a non-source text file: only a Proofly header near the top is looked at."""
    rel = rel if rel is not None else path
    expected = expected_license(rel)
    text, why = _read(path)
    if text is None:
        return Result(path, "skipped", why, expected)
    head = text.splitlines()[:HEADER_SEARCH_LINES]
    if not any(COPYRIGHT_RE.search(line) for line in head):
        return Result(path, "skipped", "no Proofly header", expected)
    ids = _spdx_ids(head)
    if not ids or any(found not in OWN_LICENSES for found in ids):
        return Result(path, "skipped", "no Proofly SPDX line", expected)
    status, detail = inspect_text(text, expected, accepted_licenses(rel))
    if status == "missing":  # a copyright line without SPDX is not ours to manage here
        return Result(path, "skipped", detail, expected)
    return Result(path, status, detail, expected)


def fix_file(path: Path, rel: PurePosixPath | Path | str | None = None) -> bool:
    """Insert or correct the header. Returns True when the file changed."""
    rel = rel if rel is not None else path
    license_id = expected_license(rel)
    text = path.read_text(encoding="utf-8")
    suffix = path.suffix.lower()
    if suffix in COMMENT_STYLES:
        new_text = add_header(text, suffix, license_id)
    else:
        new_text = retag_text(text, license_id)
    if new_text == text:
        return False
    # newline="" keeps the line endings exactly as they are in new_text.
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write(new_text)
    return True


def _git_files(root: Path, *extra: str) -> list[str]:
    out = subprocess.run(  # noqa: S603
        ["git", "ls-files", "-z", *extra],  # noqa: S607
        cwd=root,
        check=True,
        capture_output=True,
    ).stdout
    return [name for name in out.decode("utf-8").split("\0") if name]


def repo_root(start: Path) -> Path:
    out = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],  # noqa: S607
        cwd=start,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    return Path(out)


def list_repo_files(root: Path) -> list[Path]:
    """Tracked files plus untracked files that are not ignored."""
    names = set(_git_files(root)) | set(_git_files(root, "--others", "--exclude-standard"))
    return [root / name for name in sorted(names)]


def _relative(path: Path, root: Path | None) -> PurePosixPath:
    if root is not None:
        try:
            return PurePosixPath(path.resolve().relative_to(root.resolve()).as_posix())
        except ValueError:
            pass
    return PurePosixPath(path.as_posix())


def select(paths: Iterable[Path], root: Path | None = None) -> list[Path]:
    """Source files (COMMENT_STYLES types) among paths."""
    return [path for path in paths if is_candidate(_relative(path, root))]


def select_secondary(paths: Iterable[Path], root: Path | None = None) -> list[Path]:
    """Other text files among paths (checked only when they carry a Proofly header)."""
    return [path for path in paths if is_secondary(_relative(path, root))]


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="report files that need attention")
    mode.add_argument("--fix", action="store_true", help="insert or correct headers")
    parser.add_argument("paths", nargs="*", type=Path, help="files to check (default: repo files)")
    args = parser.parse_args(argv)

    root: Path | None
    if args.paths:
        try:
            root = repo_root(Path.cwd())
        except (subprocess.CalledProcessError, FileNotFoundError):
            root = None
        paths = list(args.paths)
    else:
        root = repo_root(Path.cwd())
        paths = list_repo_files(root)

    results = [check_file(path, _relative(path, root)) for path in select(paths, root)]
    results += [
        check_secondary(path, _relative(path, root)) for path in select_secondary(paths, root)
    ]
    checked = [r for r in results if r.status != "skipped"]
    fixable = [r for r in results if r.status in {"missing", "wrong-license"}]
    other = [r for r in results if r.status == "other-license"]

    if args.fix:
        fixed = [r for r in fixable if fix_file(r.path, _relative(r.path, root))]
        for r in fixed:
            verb = "relicensed header" if r.status == "wrong-license" else "added header"
            print(f"{verb} ({r.expected}): {r.path}")
        for r in other:
            print(f"left unchanged ({r.detail}): {r.path}", file=sys.stderr)
        print(f"{len(fixed)} file(s) fixed, {len(other)} file(s) need manual review.")
        return 1 if other else 0

    for r in results:
        if r.status == "missing":
            print(f"missing header ({r.detail}): {r.path}")
        elif r.status == "wrong-license":
            print(f"wrong license for this folder ({r.detail}): {r.path}")
        elif r.status == "other-license":
            print(f"different license ({r.detail}): {r.path}")
    if fixable or other:
        print(
            f"{len(fixable) + len(other)} file(s) need attention. "
            "Run: python scripts/spdx_headers.py --fix",
            file=sys.stderr,
        )
        return 1
    print(f"SPDX headers OK in {len(checked)} file(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
