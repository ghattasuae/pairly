"""Check or insert the SPDX license header in every source file.

Usage:
    python scripts/spdx_headers.py --check          # exit 1 and list files missing the header
    python scripts/spdx_headers.py --fix            # insert the header where it is missing
    python scripts/spdx_headers.py --check a.py b.ts  # only look at the given files

With no paths, the file list is every tracked file plus every untracked file
that git does not ignore (`git ls-files` and `git ls-files --others --exclude-standard`).

The header is two comment lines, written with the comment syntax of the file type:

    SPDX-License-Identifier: AGPL-3.0-only
    Copyright (c) 2026 Proofly Technology

Shebang lines, Python encoding lines and CSS `@charset` rules stay on top.
Files that carry a different SPDX identifier are reported and never changed.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

LICENSE_ID = "AGPL-3.0-only"
COPYRIGHT = "Copyright (c) 2026 Proofly Technology"
SPDX_LINE = f"SPDX-License-Identifier: {LICENSE_ID}"

# How many lines from the top we search for an existing header.
HEADER_SEARCH_LINES = 10

# Comment syntax per file extension: (prefix, suffix).
COMMENT_STYLES: dict[str, tuple[str, str]] = {
    ".py": ("# ", ""),
    ".sh": ("# ", ""),
    ".yaml": ("# ", ""),
    ".yml": ("# ", ""),
    ".ts": ("// ", ""),
    ".tsx": ("// ", ""),
    ".js": ("// ", ""),
    ".mjs": ("// ", ""),
    ".cjs": ("// ", ""),
    ".css": ("/* ", " */"),
    ".sql": ("-- ", ""),
}

SKIP_DIR_PARTS = frozenset(
    {
        "node_modules",
        ".venv",
        "venv",
        ".git",
        "dist",
        "build",
        ".next",
        ".turbo",
        "coverage",
        "__pycache__",
        ".mypy_cache",
        ".ruff_cache",
        ".pytest_cache",
        "generated",
        "__generated__",
        # Third-party code kept verbatim under its own license (infra/api-docs/vendor).
        "vendor",
    }
)

SKIP_FILE_NAMES = frozenset(
    {
        "LICENSE",
        "BRIEF.md",
        "uv.lock",
        "pnpm-lock.yaml",
        "package-lock.json",
        "yarn.lock",
        "poetry.lock",
        "Cargo.lock",
        "next-env.d.ts",
    }
)

# Suffix patterns for generated or minified files.
SKIP_NAME_SUFFIXES = (".lock", ".min.js", ".min.css", ".gen.ts", ".gen.js")

# Markers that say a file is generated and must not be edited by hand.
GENERATED_MARKERS = ("@generated", "DO NOT EDIT", "Code generated by")

SPDX_RE = re.compile(r"SPDX-License-Identifier:\s*(?P<id>[^\s*]+)")
COPYRIGHT_RE = re.compile(r"Copyright \(c\) \d{4}(?:-\d{4})? Proofly Technology")
# PEP 263 encoding declaration.
ENCODING_RE = re.compile(r"^[ \t\f]*#.*?coding[:=][ \t]*[-\w.]+")


@dataclass(frozen=True)
class Result:
    """Outcome of checking one file."""

    path: Path
    status: str  # "ok", "missing", "other-license", "skipped"
    detail: str = ""


def header_lines(suffix: str) -> list[str]:
    """Return the two header lines for a file extension, without line endings."""
    prefix, end = COMMENT_STYLES[suffix]
    return [f"{prefix}{SPDX_LINE}{end}", f"{prefix}{COPYRIGHT}{end}"]


def is_candidate(path: PurePosixPath | Path) -> bool:
    """True when the path is a source file type we manage and is not excluded."""
    p = PurePosixPath(str(path).replace("\\", "/"))
    if p.name in SKIP_FILE_NAMES:
        return False
    if any(part in SKIP_DIR_PARTS for part in p.parts[:-1]):
        return False
    lowered = p.name.lower()
    if lowered.endswith(SKIP_NAME_SUFFIXES):
        return False
    return p.suffix.lower() in COMMENT_STYLES


def looks_generated(text: str) -> bool:
    head = "\n".join(text.splitlines()[:HEADER_SEARCH_LINES])
    return any(marker in head for marker in GENERATED_MARKERS)


def _preamble_length(lines: Sequence[str], suffix: str) -> int:
    """Number of leading lines that must stay above the header."""
    count = 0
    if lines and lines[0].startswith("#!"):
        count = 1
    if suffix == ".py":
        # PEP 263: the encoding line may be on line 1 or 2.
        for idx in range(count, min(2, len(lines))):
            if ENCODING_RE.match(lines[idx]):
                count = idx + 1
                break
    if suffix == ".css" and lines and lines[0].lstrip().startswith("@charset"):
        count = 1
    return count


def inspect_text(text: str) -> tuple[str, str]:
    """Classify file text. Returns (status, detail)."""
    head = text.splitlines()[:HEADER_SEARCH_LINES]
    found_id = None
    has_copyright = False
    for line in head:
        match = SPDX_RE.search(line)
        if match and found_id is None:
            found_id = match.group("id")
        if COPYRIGHT_RE.search(line):
            has_copyright = True
    if found_id is not None and found_id != LICENSE_ID:
        return "other-license", f"SPDX identifier is {found_id}"
    if found_id is None:
        return "missing", "no SPDX line"
    if not has_copyright:
        return "missing", "no Proofly Technology copyright line"
    return "ok", ""


def add_header(text: str, suffix: str) -> str:
    """Return text with the header inserted. Text that already has it is returned unchanged."""
    status, _ = inspect_text(text)
    if status != "missing":
        return text
    newline = "\r\n" if "\r\n" in text else "\n"
    lines = text.splitlines(keepends=True)
    bare = [line.rstrip("\r\n") for line in lines]
    keep = _preamble_length(bare, suffix)

    # A file that has the SPDX line but not the copyright line: add the copyright under it.
    for idx, line in enumerate(bare[:HEADER_SEARCH_LINES]):
        if SPDX_RE.search(line):
            copyright_line = header_lines(suffix)[1] + newline
            if not lines[idx].endswith(("\n", "\r")):
                lines[idx] += newline
            lines.insert(idx + 1, copyright_line)
            return "".join(lines)

    header = [line + newline for line in header_lines(suffix)]
    before = lines[:keep]
    after = lines[keep:]
    if before and not before[-1].endswith(("\n", "\r")):
        before[-1] += newline
    if after and after[0].strip():
        header.append(newline)
    return "".join(before + header + after)


def check_file(path: Path) -> Result:
    if not path.is_file():
        return Result(path, "skipped", "not a file")
    try:
        text = path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError) as exc:
        return Result(path, "skipped", f"unreadable: {exc.__class__.__name__}")
    if not text.strip():
        return Result(path, "skipped", "empty file")
    if looks_generated(text):
        return Result(path, "skipped", "generated file")
    status, detail = inspect_text(text)
    return Result(path, status, detail)


def fix_file(path: Path) -> bool:
    """Insert the header if missing. Returns True when the file changed."""
    text = path.read_text(encoding="utf-8")
    new_text = add_header(text, path.suffix.lower())
    if new_text == text:
        return False
    # newline="" keeps the line endings exactly as they are in new_text.
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write(new_text)
    return True


def _git_files(root: Path, *extra: str) -> list[str]:
    out = subprocess.run(  # noqa: S603
        ["git", "ls-files", "-z", *extra],  # noqa: S607
        cwd=root,
        check=True,
        capture_output=True,
    ).stdout
    return [name for name in out.decode("utf-8").split("\0") if name]


def repo_root(start: Path) -> Path:
    out = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],  # noqa: S607
        cwd=start,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    return Path(out)


def list_repo_files(root: Path) -> list[Path]:
    """Tracked files plus untracked files that are not ignored."""
    names = set(_git_files(root)) | set(_git_files(root, "--others", "--exclude-standard"))
    return [root / name for name in sorted(names)]


def select(paths: Iterable[Path], root: Path | None = None) -> list[Path]:
    selected = []
    for path in paths:
        rel = path
        if root is not None:
            try:
                rel = path.resolve().relative_to(root.resolve())
            except ValueError:
                rel = path
        if is_candidate(PurePosixPath(rel.as_posix())):
            selected.append(path)
    return selected


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="report files missing the header")
    mode.add_argument("--fix", action="store_true", help="insert the header where it is missing")
    parser.add_argument("paths", nargs="*", type=Path, help="files to check (default: repo files)")
    args = parser.parse_args(argv)

    if args.paths:
        root = None
        try:
            root = repo_root(Path.cwd())
        except (subprocess.CalledProcessError, FileNotFoundError):
            root = None
        files = select(args.paths, root)
    else:
        root = repo_root(Path.cwd())
        files = select(list_repo_files(root), root)

    results = [check_file(path) for path in files]
    missing = [r for r in results if r.status == "missing"]
    other = [r for r in results if r.status == "other-license"]

    if args.fix:
        fixed = [r.path for r in missing if fix_file(r.path)]
        for path in fixed:
            print(f"added header: {path}")
        for r in other:
            print(f"left unchanged ({r.detail}): {r.path}", file=sys.stderr)
        print(f"{len(fixed)} file(s) fixed, {len(other)} file(s) need manual review.")
        return 1 if other else 0

    for r in missing:
        print(f"missing header ({r.detail}): {r.path}")
    for r in other:
        print(f"different license ({r.detail}): {r.path}")
    if missing or other:
        print(
            f"{len(missing) + len(other)} file(s) need attention. "
            "Run: python scripts/spdx_headers.py --fix",
            file=sys.stderr,
        )
        return 1
    print(f"SPDX headers OK in {len(results)} file(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
