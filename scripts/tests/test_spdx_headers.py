def test_check_file_skips_empty_and_generated(tmp_path: Path) -> None:
    empty = tmp_path / "__init__.py"
    empty.write_text("")
    generated = tmp_path / "gen.ts"
    generated.write_text("// @generated by a tool\nexport {};\n")
    assert spdx.check_file(empty).status == "skipped"
    assert spdx.check_file(generated).status == "skipped"


@pytest.mark.skipif(shutil.which("git") is None, reason="git is not installed")
def test_check_and_fix_in_a_git_repo(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True)  # noqa: S607
    (tmp_path / ".gitignore").write_text("ignored.py\n")
    (tmp_path / "tracked.py").write_text("x = 1\n")
    (tmp_path / "untracked.ts").write_text("export const y = 2;\n")
    (tmp_path / "ignored.py").write_text("z = 3\n")
    (tmp_path / "notes.md").write_text("# Notes\n")
    good = tmp_path / "good.sql"
    good.write_text(f"-- {SPDX}\n-- {COPY}\n\nSELECT 1;\n")
    subprocess.run(["git", "add", "tracked.py"], cwd=tmp_path, check=True)  # noqa: S607
    monkeypatch.chdir(tmp_path)

    assert spdx.main(["--check"]) == 1
    out = capsys.readouterr().out
    assert "tracked.py" in out
    assert "untracked.ts" in out
    assert "ignored.py" not in out
    assert "notes.md" not in out
    assert "good.sql" not in out

    assert spdx.main(["--fix"]) == 0
    assert (tmp_path / "tracked.py").read_text().startswith(f"# {SPDX}\n# {COPY}\n")
    assert (tmp_path / "untracked.ts").read_text().startswith(f"// {SPDX}\n")
    assert (tmp_path / "ignored.py").read_text() == "z = 3\n"
    assert (tmp_path / "notes.md").read_text() == "# Notes\n"

    assert spdx.main(["--check"]) == 0


def test_explicit_paths(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.chdir(tmp_path)
    target = tmp_path / "one.js"
    target.write_text("console.log(1);\n")
    assert spdx.main(["--check", str(target)]) == 1
    assert spdx.main(["--fix", str(target)]) == 0
    assert spdx.main(["--check", str(target)]) == 0
