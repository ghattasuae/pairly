from types import ModuleType

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "spdx_headers.py"


def _load() -> ModuleType:
    spec = importlib.util.spec_from_file_location("spdx_headers", SCRIPT)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["spdx_headers"] = module
    spec.loader.exec_module(module)
    return module


spdx = _load()

SPDX = "SPDX-License-Identifier: AGPL-3.0-only OR LicenseRef-Proofly-Commercial"
APACHE = "SPDX-License-Identifier: Apache-2.0"
LEGACY = "SPDX-License-Identifier: AGPL-3.0-only"
COPY = "Copyright (c) 2026 Proofly Technology"


@pytest.mark.parametrize(
    ("suffix", "first", "second"),
    [
        (".py", f"# {SPDX}", f"# {COPY}"),
        (".sh", f"# {SPDX}", f"# {COPY}"),
        (".yaml", f"# {SPDX}", f"# {COPY}"),
        (".yml", f"# {SPDX}", f"# {COPY}"),
        (".ts", f"// {SPDX}", f"// {COPY}"),
        (".tsx", f"// {SPDX}", f"// {COPY}"),
        (".js", f"// {SPDX}", f"// {COPY}"),
        (".mjs", f"// {SPDX}", f"// {COPY}"),
        (".cjs", f"// {SPDX}", f"// {COPY}"),
        (".css", f"/* {SPDX} */", f"/* {COPY} */"),
        (".sql", f"-- {SPDX}", f"-- {COPY}"),
    ],
)
def test_comment_syntax(suffix: str, first: str, second: str) -> None:
    out = spdx.add_header("body\n", suffix)
    assert out.splitlines()[:3] == [first, second, ""]
    assert out.endswith("body\n")


def test_add_header_is_idempotent() -> None:
    once = spdx.add_header("print('hi')\n", ".py")
    assert spdx.add_header(once, ".py") == once
    assert spdx.inspect_text(once) == ("ok", "")


def test_shebang_stays_first() -> None:
    out = spdx.add_header("#!/usr/bin/env bash\necho hi\n", ".sh")
    lines = out.splitlines()
    assert lines[0] == "#!/usr/bin/env bash"
    assert lines[1] == f"# {SPDX}"
    assert lines[2] == f"# {COPY}"
    assert lines[-1] == "echo hi"


def test_python_shebang_and_encoding_stay_on_top() -> None:
    src = "#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\nimport os\n"
    lines = spdx.add_header(src, ".py").splitlines()
    assert lines[:4] == [
        "#!/usr/bin/env python3",
        "# -*- coding: utf-8 -*-",
        f"# {SPDX}",
        f"# {COPY}",
    ]


def test_python_encoding_on_first_line() -> None:
    lines = spdx.add_header("# coding: latin-1\nx = 1\n", ".py").splitlines()
    assert lines[0] == "# coding: latin-1"
    assert lines[1] == f"# {SPDX}"


def test_css_charset_stays_first() -> None:
    lines = spdx.add_header('@charset "utf-8";\nbody {}\n', ".css").splitlines()
    assert lines[0] == '@charset "utf-8";'
    assert lines[1] == f"/* {SPDX} */"


def test_crlf_is_preserved() -> None:
    out = spdx.add_header("a = 1\r\nb = 2\r\n", ".py")
    assert out.startswith(f"# {SPDX}\r\n# {COPY}\r\n\r\na = 1\r\n")


def test_missing_copyright_line_is_added_under_spdx() -> None:
    src = f"// {SPDX}\nexport const x = 1;\n"
    assert spdx.inspect_text(src)[0] == "missing"
    out = spdx.add_header(src, ".ts")
    assert out.splitlines()[:2] == [f"// {SPDX}", f"// {COPY}"]
    assert spdx.inspect_text(out) == ("ok", "")


def test_other_license_is_reported_and_not_changed() -> None:
    src = "# SPDX-License-Identifier: MIT\nx = 1\n"
    assert spdx.inspect_text(src)[0] == "other-license"
    assert spdx.add_header(src, ".py") == src


