"""Export every workflow's LangGraph graphs to Mermaid, from the real graph definitions.

    uv run python -m scripts.export_graphs           # write docs/graphs/*.md
    uv run python -m scripts.export_graphs --check   # exit 1 if a file would change

The graphs are found the way the API and the worker find them: through the
``pairly.workflows`` entry points (``discover_plugins``). Each ``GraphSpec`` is built and
compiled without a checkpointer, and LangGraph draws it (``draw_mermaid``). One file per
graph, plus ``docs/graphs/README.md`` as the index, and every diagram again inside the
``graphs:begin`` / ``graphs:end`` block of ``docs/architecture.md``. A test regenerates
them and fails on any difference, so the diagrams cannot drift from the code.

Solid arrows are fixed edges; dotted arrows are conditional edges (the node picks one).
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Iterable
from pathlib import Path
from typing import Any, Final

ROOT: Final = Path(__file__).resolve().parents[1]
OUT: Final = ROOT / "docs" / "graphs"
ARCHITECTURE: Final = ROOT / "docs" / "architecture.md"
BEGIN: Final = "<!-- graphs:begin -->"
END: Final = "<!-- graphs:end -->"
HEADER: Final = (
    "<!-- Generated by `uv run python -m scripts.export_graphs` from the graph code. "
    "Do not edit by hand. -->"
)


def _specs() -> list[tuple[str, str, Any]]:
    from pairly_core.plugins import discover_plugins

    out: list[tuple[str, str, Any]] = []
    for plugin_id, plugin in sorted(discover_plugins().items()):
        for spec in plugin.graphs:
            out.append((plugin_id, plugin.name, spec))
    return out


def _mermaid(spec: Any) -> str:
    compiled = spec.build().compile()
    text: str = compiled.get_graph().draw_mermaid()
    return text.strip().replace("\t", "    ")


def _names(values: Iterable[str]) -> str:
    listed = sorted(values)
    return ", ".join(f"`{v}`" for v in listed) if listed else "none"


def render_graph(plugin_name: str, spec: Any) -> str:
    approvals = [a.key for a in spec.approval_types]
    lines = [
        HEADER,
        "",
        f"# `{spec.name}` ({plugin_name})",
        "",
        spec.description or "No description.",
        "",
        f"* Workflow: `{spec.workflow}`, graph version {spec.version}.",
        f"* Started with `{spec.start_permission}`, read with `{spec.read_permission}`.",
        f"* Approval types: {_names(approvals)}.",
        f"* Final actions (run by the engine after a person approves): "
        f"{_names(spec.final_actions)}.",
        "",
        "```mermaid",
        _mermaid(spec),
        "```",
        "",
    ]
    return "\n".join(lines)


def render() -> dict[str, str]:
    """File name (in ``docs/graphs``) to its content."""
    files: dict[str, str] = {}
    index = [
        HEADER,
        "",
        "# Workflow graphs",
        "",
        "Every LangGraph graph the workflows register, drawn from the code. Solid arrows",
        "are fixed edges, dotted arrows are conditional edges. A graph that waits for a",
        "person stops at an interrupt and resumes when the approval is decided.",
        "",
        "| Workflow | Graph | Version | Approval types | File |",
        "|---|---|---|---|---|",
    ]
    for plugin_id, plugin_name, spec in _specs():
        name = f"{spec.name}.md"
        files[name] = render_graph(plugin_name, spec)
        approvals = _names(a.key for a in spec.approval_types)
        index.append(
            f"| {plugin_id} | `{spec.name}` | {spec.version} | {approvals} | [{name}]({name}) |"
        )
    index.append("")
    files["README.md"] = "\n".join(index)
    return files


def render_block() -> str:
    """The architecture page's graph block: every diagram, under its own heading."""
    parts = [BEGIN]
    for _, plugin_name, spec in _specs():
        parts += [
            "",
            f"### `{spec.name}` ({plugin_name})",
            "",
            f"{spec.description or 'No description.'} [Details](graphs/{spec.name}.md).",
            "",
            "```mermaid",
            _mermaid(spec),
            "```",
        ]
    parts += ["", END]
    return "\n".join(parts)


def with_block(page: str) -> str:
    """``page`` with its graph block replaced by the current one."""
    if BEGIN not in page or END not in page:
        raise SystemExit(f"{ARCHITECTURE.name}: missing {BEGIN} / {END}")
    head, rest = page.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + render_block() + tail


def stale(out: Path = OUT, architecture: Path = ARCHITECTURE) -> list[str]:
    """Files that are missing, different or no longer generated."""
    wanted = render()
    changed = [
        name
        for name, text in wanted.items()
        if not (out / name).is_file() or (out / name).read_text(encoding="utf-8") != text
    ]
    extra = [p.name for p in out.glob("*.md") if p.name not in wanted] if out.is_dir() else []
    if architecture.is_file():
        page = architecture.read_text(encoding="utf-8")
        if with_block(page) != page:
            changed.append(architecture.name)
    return sorted(changed + extra)


def write(out: Path = OUT, architecture: Path = ARCHITECTURE) -> list[str]:
    out.mkdir(parents=True, exist_ok=True)
    wanted = render()
    for p in out.glob("*.md"):
        if p.name not in wanted:
            p.unlink()
    for name, text in wanted.items():
        (out / name).write_text(text, encoding="utf-8")
    written = [f"graphs/{name}" for name in sorted(wanted)]
    if architecture.is_file():
        page = architecture.read_text(encoding="utf-8")
        architecture.write_text(with_block(page), encoding="utf-8")
        written.append(architecture.name)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="fail if a file would change")
    args = parser.parse_args(argv)
    if args.check:
        changed = stale()
        for name in changed:
            print(f"{name} is out of date", file=sys.stderr)
        if changed:
            print("run: uv run python -m scripts.export_graphs", file=sys.stderr)
        return 1 if changed else 0
    for name in write():
        print(f"docs/{name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
