"""Write the "Real numbers" section of README.md from the eval report and results.

    uv run python -m scripts.readme_numbers           # rewrite the section in README.md
    uv run python -m scripts.readme_numbers --check   # exit 1 if the section is stale

Nothing in the section is typed by hand (BRIEF rule 9). Live numbers come from the
"Live baseline" table and header of ``evals/report.md`` (written by
``python -m evals.live report``); the scripted and deterministic numbers come from
``evals/results/hire.json``, ``guardrails_hire.json`` and ``pay.json`` (written by
``make evals``). Values are printed exactly as the source holds them. A missing row or
key fails the script, it is never filled in.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
REPORT = ROOT / "evals" / "report.md"
RESULTS = ROOT / "evals" / "results"
BEGIN = "<!-- BEGIN numbers (generated by uv run python -m scripts.readme_numbers; do not edit) -->"
END = "<!-- END numbers -->"

LIVE = "live model"
SCRIPTED = "scripted answers"
PERFECT_READER = "checks only, ground-truth reader"
DETERMINISTIC = "deterministic checks"


@dataclass(frozen=True)
class Row:
    metric: str
    value: str
    sample: str
    how: str


def _live_section(report: str) -> str:
    found = re.search(r"<!-- BEGIN live .*?-->(.*?)<!-- END live -->", report, re.S)
    if found is None:
        raise SystemExit(f"no Live baseline section in {REPORT}")
    return found.group(1)


def _live_rows(section: str) -> dict[str, tuple[str, str]]:
    rows: dict[str, tuple[str, str]] = {}
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 3 and cells[0] not in ("Metric", "") and not set(cells[0]) <= {"-"}:
            rows[cells[0]] = (cells[1], cells[2])
    return rows


def _header(section: str, label: str) -> str:
    found = re.search(rf"^- {re.escape(label)}[^:]*: (.+)$", section, re.M)
    if found is None:
        raise SystemExit(f"no '{label}' line in the Live baseline of {REPORT}")
    return found.group(1).strip()


def _get(data: dict[str, Any], dotted: str) -> Any:
    value: Any = data
    for key in dotted.split("."):
        if not isinstance(value, dict) or key not in value:
            raise SystemExit(f"missing {dotted}")
        value = value[key]
    return value


def _results(name: str) -> dict[str, Any]:
    data: dict[str, Any] = json.loads((RESULTS / f"{name}.json").read_text(encoding="utf-8"))
    return data


def rows() -> tuple[list[Row], dict[str, str]]:
    report = REPORT.read_text(encoding="utf-8")
    section = _live_section(report)
    live = _live_rows(section)

    def from_live(label: str, metric: str | None = None) -> Row:
        if label not in live:
            raise SystemExit(f"no '{label}' row in the Live baseline of {REPORT}")
        value, sample = live[label]
        return Row(metric or label, value, sample, LIVE)

    hire = _results("hire")
    guard = _results("guardrails_hire")
    pay = _results("pay")
    table = [
        from_live("Evidence validity", "Evidence validity (quotes found in the CV)"),
        from_live("CV field extraction accuracy"),
        from_live(
            "Rubric agreement, within one point (final)",
            "Scoring agreement with labels, within one point",
        ),
        from_live(
            "Fairness, input-identical pairs: max score change",
            "Fairness: score change, identical scoring input",
        ),
        from_live(
            "Fairness, input-different pairs: change above the noise",
            "Fairness: score change above model noise, other pairs",
        ),
        from_live(
            "Classifier recall (payload removed)", "Injection classifier recall (payload removed)"
        ),
        from_live("Classifier false-positive rate", "Injection classifier false-positive rate"),
        Row(
            "Guardrails precision / recall / false-positive rate (CVs)",
            f"{_get(guard, 'document_level.precision')} / {_get(guard, 'document_level.recall')} / "
            f"{_get(guard, 'document_level.false_positive_rate')}",
            f"{_get(guard, 'documents.guardrail_attacks')} attacks, "
            f"{_get(guard, 'documents.clean')} clean",
            f"{DETERMINISTIC}, classifier off",
        ),
        Row(
            "Evidence validity, whole pipeline",
            str(_get(hire, "evidence_validity.rate")),
            f"{_get(hire, 'evidence_validity.quotes')} quotes",
            SCRIPTED,
        ),
        Row(
            "Invoice injection catch rate",
            str(_get(pay, "injection.catch_rate")),
            f"{_get(pay, 'injection.positives')} attacks",
            PERFECT_READER,
        ),
        Row(
            "Bank-mismatch recall",
            str(_get(pay, "bank_mismatch.recall")),
            f"{_get(pay, 'bank_mismatch.positives')} attacks",
            PERFECT_READER,
        ),
        Row(
            "Duplicate recall / precision",
            f"{_get(pay, 'duplicates.recall')} / {_get(pay, 'duplicates.precision')}",
            f"{_get(pay, 'duplicates.positives')} duplicates",
            PERFECT_READER,
        ),
        from_live("Invoice header field accuracy"),
        from_live("Invoice line-item field accuracy"),
        from_live("Invoice total accuracy"),
        from_live("Invoice VAT accuracy"),
        from_live("Cost per CV, mean USD"),
        from_live("Cost per invoice, mean USD"),
    ]
    facts = {
        "date": _header(section, "Date (UTC)"),
        "models": _header(section, "Models answering"),
        "spend": _header(section, "Total spent on live calls"),
    }
    return table, facts


def section() -> str:
    table, facts = rows()
    lines = [
        BEGIN,
        "",
        "Every number below comes from `evals/report.md` and `evals/results/`. All data is",
        "synthetic: generated CVs and invoices with rule-based labels, not real people,",
        "invoices or human judgments. The last column says how each was measured:",
        "",
        f"- **{LIVE}**: a real model answered (the live baseline, `python -m evals.live`).",
        f"- **{SCRIPTED}**: the model steps were answered from the synthetic ground truth, so",
        "  the number tests the code around the model, not the model.",
        f"- **{PERFECT_READER}**: the invoice checks ran on the true values, as if the",
        "  reading were perfect.",
        f"- **{DETERMINISTIC}**: no model involved.",
        "",
        "| Metric | Value | Sample | Measured with |",
        "|---|---|---|---|",
        *(f"| {r.metric} | {r.value} | {r.sample} | {r.how} |" for r in table),
        "",
        f"- Live baseline date (UTC): {facts['date']}",
        f"- Model ids (calls): {facts['models']}",
        f"- Total live spend, smoke runs included: {facts['spend']}",
        "- Thresholds and the gate: `evals/thresholds.yaml`. The live numbers do not gate yet.",
        "",
        END,
    ]
    return "\n".join(lines)


def rendered(readme: str) -> str:
    start, stop = readme.find(BEGIN), readme.find(END)
    if start < 0 or stop < 0:
        raise SystemExit(f"README.md has no {BEGIN} ... {END} markers")
    return readme[:start] + section() + readme[stop + len(END) :]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m scripts.readme_numbers")
    parser.add_argument("--check", action="store_true", help="exit 1 if README.md is stale")
    args = parser.parse_args(argv)
    current = README.read_text(encoding="utf-8")
    wanted = rendered(current)
    if args.check:
        if wanted != current:
            print(
                "README.md numbers are stale: run uv run python -m scripts.readme_numbers",
                file=sys.stderr,
            )
            return 1
        return 0
    if wanted != current:
        README.write_text(wanted, encoding="utf-8")
        print("README.md: numbers section rewritten")
    else:
        print("README.md: numbers section unchanged")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
