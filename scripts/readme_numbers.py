"""Write the generated sections of README.md: "Real numbers" and "By the numbers".

    uv run python -m scripts.readme_numbers           # rewrite both sections
    uv run python -m scripts.readme_numbers --check   # exit 1 if "Real numbers" is stale

"By the numbers" counts the repository (lines by language, tests, migrations, specs,
gated metrics, UI languages) from the files git tracks at HEAD and names the date of
that commit, not its hash: pull requests are squash merged, so the hash of the commit a
branch counted at never reaches main. It changes with every commit, so ``--check`` does
not compare it; rerun the script to refresh it before a release.

Nothing in the section is typed by hand (BRIEF rule 9). Live numbers come from the
"Live baseline" table and header of ``evals/report.md`` (written by
``python -m evals.live report``); the scripted and deterministic numbers come from
``evals/results/hire.json``, ``guardrails_hire.json`` and ``pay.json`` (written by
``make evals``). Values are printed exactly as the source holds them. A missing row or
key fails the script, it is never filled in.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
REPORT = ROOT / "evals" / "report.md"
RESULTS = ROOT / "evals" / "results"
BEGIN = "<!-- BEGIN numbers (generated by uv run python -m scripts.readme_numbers; do not edit) -->"
END = "<!-- END numbers -->"
STATS_BEGIN = (
    "<!-- BEGIN repo-stats (generated by uv run python -m scripts.readme_numbers; do not edit) -->"
)
STATS_END = "<!-- END repo-stats -->"

# Lines of code: tracked files by extension; generated files and lock files left out.
LANGUAGES = {
    ".py": "Python",
    ".ts": "TypeScript",
    ".tsx": "TypeScript (React)",
    ".sql": "SQL",
    ".sh": "Shell",
    ".md": "Markdown (docs, prompts)",
}
GENERATED = ("packages/shared-ts/src/generated/", "packages/shared-ts/openapi/")

LIVE = "live model"
SCRIPTED = "scripted answers"
PERFECT_READER = "checks only, ground-truth reader"
DETERMINISTIC = "deterministic checks"


@dataclass(frozen=True)
class Row:
    metric: str
    value: str
    sample: str
    how: str


def _live_section(report: str) -> str:
    found = re.search(r"<!-- BEGIN live .*?-->(.*?)<!-- END live -->", report, re.S)
    if found is None:
        raise SystemExit(f"no Live baseline section in {REPORT}")
    return found.group(1)


def _live_rows(section: str) -> dict[str, tuple[str, str]]:
    rows: dict[str, tuple[str, str]] = {}
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 3 and cells[0] not in ("Metric", "") and not set(cells[0]) <= {"-"}:
            rows[cells[0]] = (cells[1], cells[2])
    return rows


def _header(section: str, label: str) -> str:
    found = re.search(rf"^- {re.escape(label)}[^:]*: (.+)$", section, re.M)
    if found is None:
        raise SystemExit(f"no '{label}' line in the Live baseline of {REPORT}")
    return found.group(1).strip()


def _get(data: dict[str, Any], dotted: str) -> Any:
    value: Any = data
    for key in dotted.split("."):
        if not isinstance(value, dict) or key not in value:
            raise SystemExit(f"missing {dotted}")
        value = value[key]
    return value


def _results(name: str) -> dict[str, Any]:
    data: dict[str, Any] = json.loads((RESULTS / f"{name}.json").read_text(encoding="utf-8"))
    return data


def _live_gates() -> str:
    """One sentence on the live metrics the gate reads, counted from the thresholds file."""
    from evals.gate import THRESHOLDS, load_thresholds

    live = [
        m
        for m in load_thresholds(THRESHOLDS)
        if m.get("live") is True and not m.get("informational")
    ]
    if not live:
        return "The live numbers do not gate yet."
    return (
        f"{len(live)} of the live numbers gate merges (`live: true`, read from the committed "
        "`*_live.json` files); `python -m evals.gate` marks them LIVE."
    )


def rows() -> tuple[list[Row], dict[str, str]]:
    report = REPORT.read_text(encoding="utf-8")
    section = _live_section(report)
    live = _live_rows(section)

    def from_live(label: str, metric: str | None = None) -> Row:
        if label not in live:
            raise SystemExit(f"no '{label}' row in the Live baseline of {REPORT}")
        value, sample = live[label]
        return Row(metric or label, value, sample, LIVE)

    hire = _results("hire")
    guard = _results("guardrails_hire")
    pay = _results("pay")
    table = [
        from_live("Evidence validity", "Evidence validity (quotes found in the CV)"),
        from_live("CV field extraction accuracy"),
        from_live(
            "Rubric agreement, within one point (final)",
            "Scoring agreement with labels, within one point",
        ),
        from_live(
            "Fairness, input-identical pairs: max score change",
            "Fairness: score change, identical scoring input",
        ),
        from_live(
            "Fairness, input-different pairs: change above the noise",
            "Fairness: score change above model noise, other pairs",
        ),
        from_live(
            "Classifier recall (payload removed)", "Injection classifier recall (payload removed)"
        ),
        from_live("Classifier false-positive rate", "Injection classifier false-positive rate"),
        Row(
            "Guardrails precision / recall / false-positive rate (CVs)",
            f"{_get(guard, 'document_level.precision')} / {_get(guard, 'document_level.recall')} / "
            f"{_get(guard, 'document_level.false_positive_rate')}",
            f"{_get(guard, 'documents.guardrail_attacks')} attacks, "
            f"{_get(guard, 'documents.clean')} clean",
            f"{DETERMINISTIC}, classifier off",
        ),
        Row(
            "Evidence validity, whole pipeline",
            str(_get(hire, "evidence_validity.rate")),
            f"{_get(hire, 'evidence_validity.quotes')} quotes",
            SCRIPTED,
        ),
        Row(
            "Invoice injection catch rate",
            str(_get(pay, "injection.catch_rate")),
            f"{_get(pay, 'injection.positives')} attacks",
            PERFECT_READER,
        ),
        Row(
            "Bank-mismatch recall",
            str(_get(pay, "bank_mismatch.recall")),
            f"{_get(pay, 'bank_mismatch.positives')} attacks",
            PERFECT_READER,
        ),
        Row(
            "Duplicate recall / precision",
            f"{_get(pay, 'duplicates.recall')} / {_get(pay, 'duplicates.precision')}",
            f"{_get(pay, 'duplicates.positives')} duplicates",
            PERFECT_READER,
        ),
        from_live("Invoice header field accuracy"),
        from_live("Invoice line-item field accuracy"),
        from_live("Invoice total accuracy"),
        from_live("Invoice VAT accuracy"),
        from_live("Cost per CV, mean USD"),
        from_live("Cost per invoice, mean USD"),
    ]
    facts = {
        "date": _header(section, "Date (UTC)"),
        "models": _header(section, "Models answering"),
        "spend": _header(section, "Total spent on live calls"),
    }
    return table, facts


def section() -> str:
    table, facts = rows()
    lines = [
        BEGIN,
        "",
        "Every number below comes from `evals/report.md` and `evals/results/`. All data is",
        "synthetic: generated CVs and invoices with rule-based labels, not real people,",
        "invoices or human judgments. The last column says how each was measured:",
        "",
        f"- **{LIVE}**: a real model answered (the live baseline, `python -m evals.live`).",
        f"- **{SCRIPTED}**: the model steps were answered from the synthetic ground truth, so",
        "  the number tests the code around the model, not the model.",
        f"- **{PERFECT_READER}**: the invoice checks ran on the true values, as if the",
        "  reading were perfect.",
        f"- **{DETERMINISTIC}**: no model involved.",
        "",
        "| Metric | Value | Sample | Measured with |",
        "|---|---|---|---|",
        *(f"| {r.metric} | {r.value} | {r.sample} | {r.how} |" for r in table),
        "",
        f"- Live baseline date (UTC): {facts['date']}",
        f"- Model ids (calls): {facts['models']}",
        f"- Total live spend, smoke runs included: {facts['spend']}",
        f"- Thresholds and the gate: `evals/thresholds.yaml`. {_live_gates()}",
        "",
        END,
    ]
    return "\n".join(lines)


def _git(*args: str) -> str:
    return subprocess.run(  # noqa: S603 (fixed git arguments from this script)
        ["git", *args],  # noqa: S607 (git from PATH)
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout


def _tracked() -> list[str]:
    return [f for f in _git("ls-files").splitlines() if (ROOT / f).is_file()]


def _lines(path: str) -> int:
    text = (ROOT / path).read_text(encoding="utf-8", errors="replace")
    return sum(1 for line in text.splitlines() if line.strip())


def stats() -> list[tuple[str, str]]:
    """(what, value) rows counted from the tracked files."""
    files = _tracked()
    by_language: dict[str, tuple[int, int]] = {}
    for f in files:
        language = LANGUAGES.get(Path(f).suffix)
        if language is None or f.startswith(GENERATED):
            continue
        count, lines = by_language.get(language, (0, 0))
        by_language[language] = (count + 1, lines + _lines(f))
    rows = [
        (f"{language}: lines (files)", f"{lines} ({count})")
        for language, (count, lines) in sorted(by_language.items(), key=lambda kv: -kv[1][1])
    ]
    py_tests = 0
    for f in files:
        name = Path(f).name
        if f.endswith(".py") and (name.startswith("test_") or "/tests/" in f):
            py_tests += len(re.findall(r"^\s*(?:async )?def test_", (ROOT / f).read_text(), re.M))
    ts_tests = 0
    for f in files:
        if re.search(r"\.test\.tsx?$", f):
            ts_tests += len(re.findall(r"^\s*(?:it|test)\(", (ROOT / f).read_text(), re.M))
    specs = [f for f in files if f.startswith("apps/web/e2e/tests/") and f.endswith(".spec.ts")]
    e2e_tests = sum(len(re.findall(r"^test\(", (ROOT / f).read_text(), re.M)) for f in specs)
    migrations = [
        f
        for f in files
        if f.endswith(".py")
        and not f.endswith("__init__.py")
        and ("/alembic/versions/" in f or re.search(r"/pairly_\w+/migrations/", f))
    ]
    thresholds = (ROOT / "evals" / "thresholds.yaml").read_text(encoding="utf-8")
    metrics = len(re.findall(r"^\s*- id: ", thresholds, re.M))
    informational = len(re.findall(r"^\s*informational: true", thresholds, re.M))
    locales = sorted(Path(f).stem for f in files if re.fullmatch(r"apps/web/messages/\w+\.json", f))
    adrs = [f for f in files if re.fullmatch(r"docs/adr/\d{4}-.+\.md", f)]
    cards = [f for f in files if f.startswith("docs/model-cards/") and not f.endswith("README.md")]
    prompts = [f for f in files if re.search(r"/prompts/[^/]+/v\d+\.md$", f)]
    rows += [
        ("Python test functions (a parametrized test counts once)", str(py_tests)),
        ("TypeScript unit and component tests", str(ts_tests)),
        ("Playwright end-to-end specs (tests)", f"{len(specs)} ({e2e_tests})"),
        ("Database migrations (engine and plugins)", str(len(migrations))),
        ("Eval metrics in the CI gate (informational, not gating)", f"{metrics} ({informational})"),
        ("Versioned prompts", str(len(prompts))),
        ("Architecture decision records", str(len(adrs))),
        ("Model cards", str(len(cards))),
        ("UI languages", ", ".join(locales)),
    ]
    return rows


def stats_section() -> str:
    day = _git("log", "-1", "--format=%cs", "HEAD").strip()
    return "\n".join(
        [
            STATS_BEGIN,
            "",
            f"Counted on {day} from the files git tracks. Lines are non-blank",
            "lines; generated API types and lock files are left out.",
            "",
            "| What | Count |",
            "|---|---|",
            *(f"| {what} | {value} |" for what, value in stats()),
            "",
            STATS_END,
        ]
    )


def _replace(text: str, begin: str, end: str, body: str) -> str:
    start, stop = text.find(begin), text.find(end)
    if start < 0 or stop < 0:
        raise SystemExit(f"README.md has no {begin} ... {end} markers")
    return text[:start] + body + text[stop + len(end) :]


def rendered(readme: str) -> str:
    return _replace(readme, BEGIN, END, section())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m scripts.readme_numbers")
    parser.add_argument("--check", action="store_true", help="exit 1 if README.md is stale")
    args = parser.parse_args(argv)
    current = README.read_text(encoding="utf-8")
    wanted = rendered(current)
    if args.check:
        if wanted != current:
            print(
                "README.md numbers are stale: run uv run python -m scripts.readme_numbers",
                file=sys.stderr,
            )
            return 1
        return 0
    if STATS_BEGIN in wanted:
        wanted = _replace(wanted, STATS_BEGIN, STATS_END, stats_section())
    if wanted != current:
        README.write_text(wanted, encoding="utf-8")
        print("README.md: generated sections rewritten")
    else:
        print("README.md: generated sections unchanged")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
